/* Builds src/landing/landing.css from src/landing/index.css.

   src/landing/ is the NasouHive landing page copied as-is from the
   nasouhive repo. Its index.css was written to own the whole page (html,
   body, a, button, :root …), so loading it untouched would restyle the
   storefront too. This script makes a copy where every rule only applies
   inside <div class="nasou-landing">, and leaves index.css exactly as it
   came so a newer copy can be dropped in and this re-run:

     npm run build:landing-css
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src/landing/index.css');
const out = path.join(root, 'src/landing/landing.css');
const SCOPE = '.nasou-landing';

/* The storefront has its own `drift` and `pulse-ring` animations, so the
   landing's keyframes get a prefix to keep both. */
const renameAnim = (name) => `landing-${name}`;

const css = postcss.parse(fs.readFileSync(src, 'utf8'), { from: src });
const keyframes = new Set();

css.walkAtRules((at) => {
  // the storefront already loads Tailwind (with its own theme)
  if (at.name === 'import' && /["']tailwindcss["']/.test(at.params)) at.remove();
  if (at.name === 'keyframes') {
    keyframes.add(at.params);
    at.params = renameAnim(at.params);
  }
});

const scopeSelector = (sel) => {
  if (['html', 'body', ':root', '#root'].includes(sel)) return SCOPE;
  if (/^(html|body)\s/.test(sel)) return sel.replace(/^(html|body)/, SCOPE);
  return `${SCOPE} ${sel}`;
};

css.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
  rule.selectors = [...new Set(rule.selectors.map(scopeSelector))];
});

css.walkDecls(/^animation(-name)?$/, (decl) => {
  decl.value = decl.value.replace(/[\w-]+/g, (w) => (keyframes.has(w) ? renameAnim(w) : w));
});

/* Where the storefront's theme and base styles differ from what the
   landing was built against (stock Tailwind), put the landing's back. */
const fixes = `
${SCOPE} {
  --radius-xl: 0.75rem;
}

@layer base {
  ${SCOPE} :is(h1, h2, h3, h4) {
    font-family: inherit;
    font-weight: inherit;
    letter-spacing: inherit;
    line-height: inherit;
    color: inherit;
  }
}
`;

const banner = `/* GENERATED by scripts/scope-landing-css.mjs from ./index.css — do not edit.
   Edit index.css (or replace it with a newer copy from nasouhive) and run
   \`npm run build:landing-css\`. */\n`;

fs.writeFileSync(out, banner + css.toString() + '\n' + fixes);
console.log(`Wrote ${path.relative(root, out)} (${keyframes.size} keyframes renamed: ${[...keyframes].join(', ')})`);
